-- DDL for the scratch schema used by tests/test_real_dsql.py (one statement per ';' at end of line).
-- Mirrors production; `workout.` is rewritten to the test schema.
CREATE TABLE IF NOT EXISTS workout.athlete (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
  cognito_sub text NOT NULL,
  username text NOT NULL,
  dob date,
  first_name text,
  last_name text,
  gender text,
  height integer,
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS workout.exercise (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
  name text NOT NULL,
  muscle_group_id bigint NOT NULL,
  difficulty real,
  complexity text,
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS workout.exercise_set (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
  lift_id bigint NOT NULL,
  position integer NOT NULL,
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS workout.exercise_subset (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
  exercise_set_id bigint NOT NULL,
  exercise_id bigint NOT NULL,
  position integer NOT NULL,
  reps integer,
  rir integer,
  weight real,
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS workout.friendship (
  requester_id integer NOT NULL,
  addressee_id integer NOT NULL,
  status text DEFAULT 'pending' NOT NULL,
  updated_at timestamp with time zone DEFAULT now() NOT NULL,
  created_at timestamp with time zone,
  requester_hides_lifts boolean,
  addressee_hides_lifts boolean,
  PRIMARY KEY (requester_id, addressee_id),
  CONSTRAINT friendship_check CHECK ((requester_id <> addressee_id))
);
CREATE TABLE IF NOT EXISTS workout.lift (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
  date date NOT NULL,
  athlete_id bigint NOT NULL,
  body_weight integer,
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS workout.muscle_group (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
  name text NOT NULL,
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS workout.program (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
  athlete_id bigint NOT NULL,
  name text NOT NULL,
  start_date date,
  end_date date,
  is_public boolean,
  assigned_by bigint,
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS workout.program_exercise_set (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
  program_lift_id bigint NOT NULL,
  position integer NOT NULL,
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS workout.program_exercise_subset (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
  program_exercise_set_id bigint NOT NULL,
  exercise_id bigint NOT NULL,
  position integer NOT NULL,
  reps integer,
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS workout.program_lift (
  id bigint GENERATED BY DEFAULT AS IDENTITY (CACHE 1) NOT NULL,
  program_id bigint NOT NULL,
  name text NOT NULL,
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS workout.coaching (
  coach_id bigint NOT NULL,
  athlete_id bigint NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  can_see_body_weight boolean NOT NULL DEFAULT false,
  created_at timestamp with time zone DEFAULT now(),
  updated_at timestamp with time zone DEFAULT now(),
  PRIMARY KEY (coach_id, athlete_id),
  CONSTRAINT coaching_check CHECK ((coach_id <> athlete_id))
);
CREATE TABLE IF NOT EXISTS workout.rate_limit (
  id uuid DEFAULT gen_random_uuid() NOT NULL,
  athlete_id bigint NOT NULL,
  action text NOT NULL,
  created_at timestamp with time zone DEFAULT now() NOT NULL,
  PRIMARY KEY (id)
);
CREATE UNIQUE INDEX ASYNC IF NOT EXISTS muscle_group_name_key ON workout.muscle_group (name);
CREATE INDEX ASYNC IF NOT EXISTS idx_exercise_muscle_group ON workout.exercise (muscle_group_id);
CREATE INDEX ASYNC IF NOT EXISTS idx_lift_athlete_date ON workout.lift (athlete_id, date);
CREATE INDEX ASYNC IF NOT EXISTS idx_exercise_set_lift ON workout.exercise_set (lift_id);
CREATE INDEX ASYNC IF NOT EXISTS idx_exercise_subset_set ON workout.exercise_subset (exercise_set_id);
CREATE INDEX ASYNC IF NOT EXISTS idx_exercise_subset_exercise ON workout.exercise_subset (exercise_id);
CREATE INDEX ASYNC IF NOT EXISTS idx_program_athlete ON workout.program (athlete_id);
CREATE INDEX ASYNC IF NOT EXISTS idx_program_lift_program ON workout.program_lift (program_id);
CREATE INDEX ASYNC IF NOT EXISTS idx_prog_ex_set_lift ON workout.program_exercise_set (program_lift_id);
CREATE INDEX ASYNC IF NOT EXISTS idx_prog_ex_subset_set ON workout.program_exercise_subset (program_exercise_set_id);
CREATE INDEX ASYNC IF NOT EXISTS idx_prog_ex_subset_exercise ON workout.program_exercise_subset (exercise_id);
CREATE UNIQUE INDEX ASYNC IF NOT EXISTS athlete_cognito_sub_key ON workout.athlete (cognito_sub);
CREATE UNIQUE INDEX ASYNC IF NOT EXISTS athlete_username_key ON workout.athlete (username);
CREATE INDEX ASYNC IF NOT EXISTS friendship_addressee_idx ON workout.friendship (addressee_id);
CREATE INDEX ASYNC IF NOT EXISTS rate_limit_lookup ON workout.rate_limit (athlete_id, action, created_at);
CREATE INDEX ASYNC IF NOT EXISTS coaching_athlete_idx ON workout.coaching (athlete_id);
